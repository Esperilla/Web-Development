// Intersection Observer for animations
const observerOptions = {
    threshold: 0.1,
    rootMargin: '0px 0px -50px 0px'
};

const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            entry.target.style.opacity = '1';
            entry.target.style.transform = 'translateY(0)';
        }
    });
}, observerOptions);

// Animate elements on scroll
document.addEventListener('DOMContentLoaded', () => {
    // Set initial styles for animation
    const animateElements = document.querySelectorAll('.service-card, .project-card, .stat, .feature');
    animateElements.forEach(el => {
        el.style.opacity = '0';
        el.style.transform = 'translateY(30px)';
        el.style.transition = 'all 0.6s ease';
        observer.observe(el);
    });

    // Counter animation for stats
    const stats = document.querySelectorAll('.stat h3');
    const statsObserver = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                const target = entry.target;
                const finalValue = target.textContent;
                let currentValue = 0;
                const increment = 1;
                const duration = 2000;
                const stepTime = duration / parseInt(finalValue.replace(/\D/g, ''));

                const timer = setInterval(() => {
                    currentValue += increment;
                    if (finalValue.includes('+')) {
                        target.textContent = currentValue + '+';
                    } else if (finalValue.includes('/')) {
                        target.textContent = currentValue + '/7';
                    } else {
                        target.textContent = currentValue;
                    }

                    if (currentValue >= parseInt(finalValue.replace(/\D/g, ''))) {
                        target.textContent = finalValue;
                        clearInterval(timer);
                    }
                }, stepTime);

                statsObserver.unobserve(target);
            }
        });
    }, { threshold: 0.5 });

    stats.forEach(stat => {
        statsObserver.observe(stat);
    });
});

